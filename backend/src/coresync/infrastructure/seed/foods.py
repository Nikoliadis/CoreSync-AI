@dataclass(frozen=True, slots=True)
class SeedFood:
    name: str
    calories: Decimal
    protein: Decimal
    carbs: Decimal
    fat: Decimal
    alcohol: Decimal
    is_liquid: bool
    servings: list[tuple[str, Decimal]]


def as_seed(food: CuratedFood) -> SeedFood:
    name, calories, protein, carbs, fat, alcohol, is_liquid, servings = food
    return SeedFood(
        name=name,
        calories=Decimal(calories),
        protein=Decimal(protein),
        carbs=Decimal(carbs),
        fat=Decimal(fat),
        alcohol=Decimal(alcohol),
        is_liquid=is_liquid,
        servings=[(label, Decimal(grams)) for label, grams in servings],
    )
